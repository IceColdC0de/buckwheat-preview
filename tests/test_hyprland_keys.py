@needs_hyprland
def test_real_hyprland_accepts_a_value_for_every_allowed_key(tmp_path: Path) -> None:
    """One sample value per kind for every key: the table matches Hyprland."""
    from buckwheat.adapters.hyprland import _render_lua

    sample: dict[str, Scalar] = {
        "bool": True,
        "int": 1,
        "float": 1.0,
        "color": "#88c0d0",
        "gradient": "#88c0d0 #b48ead 45deg",
        "gap": "1 2",
        "vec2": "1 1",
        "weight": "bold",
    }
    a = _adapter(tmp_path)
    keys = {k: i for k, i in a.lua_keys.items() if i.kind in sample}
    text = _render_lua({k: sample[i.kind] for k, i in keys.items()}, keys)
    path = tmp_path / "check.lua"
    path.write_text(text)
    rt = tmp_path / "rt"
    rt.mkdir(mode=0o700)
    res = SubprocessRunner().run(
        ["env", f"XDG_RUNTIME_DIR={rt}", str(HYPRLAND), "--verify-config", "-c"]
        + [str(path)],
        timeout=30,
    )
    out = (res.stdout + res.stderr).split("Config parsing result:")[-1]
    # Hyprland's own ranges (it checks those itself) are not what this is about.
    errors = [
        line
        for line in out.splitlines()
        if ("error setting" in line or "unknown config key" in line)
        and "than the minimum" not in line
        and "than the maximum" not in line
    ]
    assert errors == []


def test_system_prompt_with_every_hyprland_key_stays_small(tmp_path: Path) -> None:
    """The measured size goes in the PR; keep it well under ~2k tokens."""
    from buckwheat.plan import PlanContext, PlanLimits
    from buckwheat.providers import build_prompt

    a = _adapter(tmp_path)
    limits = PlanLimits(
        ops=["set", "palette", "font", "wallpaper"],
        keys={"hyprland": a.allowed_keys()},
        key_notes={"hyprland": a.describe_keys() or ""},
    )
    system = build_prompt("x", PlanContext(request_id="r", limits=limits)).system
    assert "decoration: bool" in system
    assert "general.col.active_border" not in system  # grouped, not listed
    assert len(system) < 7000
