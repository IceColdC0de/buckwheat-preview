def test_committed_data_matches_installed_stub() -> None:
    """Regenerate with scripts/gen_hyprland_keys.py if Hyprland was updated."""
    stub = Path("/usr/share/hypr/stubs/hl.meta.lua").read_text()
    assert parse_stub(stub) == _data()


def test_installed_stub_wins_over_the_data_file(tmp_path: Path) -> None:
    stub = tmp_path / "hl.meta.lua"
    stub.write_text(STUB)
    assert "future.thing" in raw_key_types(stub, DATA_PATH)
    assert raw_key_types(tmp_path / "missing.lua", DATA_PATH) == _data()


