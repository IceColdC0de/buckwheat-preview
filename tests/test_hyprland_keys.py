def test_render_nested_golden(tmp_path: Path) -> None:
    a = _adapter(tmp_path)
    text = a.render(list(VISUAL_OPS), a.read_state()).files[a.lua_managed_path]
    assert text == (FIXTURES / "visual.lua.golden").read_text()
    check_generated(a.lua_managed_path, text, home=tmp_path)


def test_render_is_deterministic_and_keeps_original_keys_first(tmp_path: Path) -> None:
    a = _adapter(tmp_path)
    ops = [*VISUAL_OPS, _set("general.gaps_in", 4)]
    first = a.render(list(ops), a.read_state()).files[a.lua_managed_path]
    again = a.render(list(reversed(ops)), a.read_state()).files[a.lua_managed_path]
    assert first == again
    general = first.split("general = {", 1)[1]
    assert general.index("gaps_in") < general.index("col = {")


def test_gap_shorthand() -> None:
    gap = KeyInfo("general.gaps_out", "gap")
    assert gap.lua(5) == "5"
    assert gap.lua("5") == "{ top = 5, right = 5, bottom = 5, left = 5 }"
    assert gap.lua("1 2 3") == "{ top = 1, right = 2, bottom = 3, left = 2 }"
    assert gap.lua("1 2 3 4") == "{ top = 1, right = 2, bottom = 3, left = 4 }"


def test_colour_rendering() -> None:
    grad = KeyInfo("general.col.active_border", "gradient")
    assert grad.lua("#88C0D0") == '"rgb(88c0d0)"'
    assert grad.lua("#88c0d0aa") == '"rgba(88c0d0aa)"'
    assert grad.lua("#88c0d0 #b48ead") == (
        '{ colors = { "rgb(88c0d0)", "rgb(b48ead)" } }'
    )


def test_strings_are_escaped_even_if_unchecked() -> None:
    text = KeyInfo("general.layout", "string").lua('a"b\\c')
    assert text == '"a\\"b\\\\c"'


