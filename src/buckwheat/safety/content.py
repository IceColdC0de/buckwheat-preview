"""The hard line: nothing buckwheat writes may run programs or reach the network.

Owner decision (2026-11-01): buckwheat may set any appearance value and write
complete stylesheets, but the content of every file it generates is checked
here before it is shown or written. A file that could start a program, bind a
key to a command, load more code, or fetch something over the network is
refused, whatever the plan said. This is defence in depth: adapters already
render only from checked values, and this check does not trust them.

Only buckwheat's own (managed) files are checked. The user's own config is
never generated by buckwheat; the bootstrap writer only adds a fixed include
block to it (``check_include_edit``).
"""

from __future__ import annotations

import re
from pathlib import Path, PurePosixPath
from urllib.parse import unquote


class UnsafeContentError(ValueError):
    """Generated text that could run a program or reach the network."""


def _refuse(path: Path, why: str) -> UnsafeContentError:
    return UnsafeContentError(f"refusing to write {path.name}: {why}")


# --- Lua (Hyprland 0.57+) ----------------------------------------------------

# Anywhere in the text, strings included: the owner's list plus Lua's own ways
# to run code or touch files.
_LUA_FORBIDDEN = re.compile(
    r"\bexec\w*|hl\s*\.\s*(?:exec_cmd|on|bind|unbind|timer|dispatch|plugin)\b"
)
_LUA_FORBIDDEN_NAMES = re.compile(
    r"\b(?:require|dofile|loadfile|loadstring|load|pcall|xpcall|os|io|package|"
    r"debug|coroutine|setmetatable|getmetatable|rawset|rawget|rawequal|_G|_ENV|"
    r"string|function|while|repeat|goto)\b"
)
_LUA_STRING = re.compile(r'"(?:[^"\\\n]|\\.)*"|' r"'(?:[^'\\\n]|\\.)*'")
_LUA_CALL = re.compile(r"([A-Za-z_][\w.:]*)\s*(?=[({\"'])")


def _check_lua(path: Path, text: str) -> None:
    found = _LUA_FORBIDDEN.search(text)
    if found:
        raise _refuse(path, f"generated Lua may not contain {found.group(0)!r}")
    if "[[" in text or "[=" in text:
        raise _refuse(path, "generated Lua may not contain long strings")
    code = _LUA_STRING.sub('""', text)
    code = re.sub(r"--[^\n]*", "", code)
    found = _LUA_FORBIDDEN_NAMES.search(code)
    if found:
        raise _refuse(path, f"generated Lua may not use {found.group(0)!r}")
    for match in _LUA_CALL.finditer(code):
        if match.group(1) != "hl.config":
            raise _refuse(
                path, f"generated Lua may only call hl.config, not {match.group(1)!r}"
            )
    for match in re.finditer(r"\bhl\s*[.:]\s*(\w+)", code):
        if match.group(1) != "config":
            raise _refuse(path, f"generated Lua may not use hl.{match.group(1)}")


# --- line-based configs (hyprlang, kitty, hyprpaper) -------------------------

# First word of a line in a ``key = value`` / ``key value`` config.
_CONF_FORBIDDEN = re.compile(
    r"^\s*(exec[\w-]*|bind\w*|unbind|source|plugin|permission|env|envinclude|"
    r"include|globinclude|geninclude|map|mouse_map|shell|launch|kitten|"
    r"action_alias|kitten_alias|startup_session|watcher|editor|open_url_with|"
    r"allow_remote_control|listen_on|remote_control_password|exe_search_path|"
    r"notify_on_cmd_finish|shell_integration|clipboard_control)\b",
    re.MULTILINE,
)


def _check_conf(path: Path, text: str) -> None:
    found = _CONF_FORBIDDEN.search(text)
    if found:
        raise _refuse(path, f"generated config may not set {found.group(1)!r}")
    if "$(" in text or "`" in text:
        raise _refuse(path, "generated config may not contain command substitution")


# --- TOML (alacritty) --------------------------------------------------------

_TOML_FORBIDDEN = re.compile(
    r"^\s*(?:\[\[?\s*[\w.\"]*\b(shell|hints|keyboard|mouse|bindings)\b"
    r"|(program|command|args|shell|import|working_directory)\s*=)",
    re.MULTILINE,
)


def _check_toml(path: Path, text: str) -> None:
    found = _TOML_FORBIDDEN.search(text)
    if found:
        what = found.group(1) or found.group(2)
        raise _refuse(path, f"generated TOML may not set {what!r}")


# --- Waybar JSON(C) -----------------------------------------------------------

_JSON_FORBIDDEN = re.compile(
    r'"(?:custom/[^"]*|exec[\w-]*|on-click[\w-]*|on-scroll[\w-]*|on-update|'
    r"include|actions)\"\s*:?"
)


def _check_json(path: Path, text: str) -> None:
    found = _JSON_FORBIDDEN.search(text)
    if found:
        raise _refuse(
            path, f"generated Waybar config may not use {found.group(0).rstrip(':')}"
        )


# --- CSS ---------------------------------------------------------------------

_CSS_URL = re.compile(r"url\s*\(\s*(['\"]?)(.*?)\1\s*\)", re.IGNORECASE | re.DOTALL)


def _local_file(ref: str, home: Path) -> bool:
    """True if a CSS url() target is a file under the user's home folder."""
    ref = unquote(ref.strip())
    if ref.startswith("file://"):
        ref = ref[len("file://") :]
    if ":" in ref or ref.startswith("//"):
        return False  # http:, https:, data:, resource: and other schemes
    if ref.startswith("~/"):
        ref = str(home) + ref[1:]
    pure = PurePosixPath(ref)
    if ".." in pure.parts:
        return False
    if not pure.is_absolute():
        return True  # relative to the stylesheet, which lives in ~/.config
    try:
        pure.relative_to(PurePosixPath(home))
    except ValueError:
        return False
    return True


def _check_css(path: Path, text: str, home: Path) -> None:
    if re.search(r"@import\b", text, re.IGNORECASE):
        raise _refuse(path, "generated CSS may not @import other stylesheets")
    if "\\" in text:
        # CSS escapes could spell url( in a way this check does not see.
        raise _refuse(path, "generated CSS may not contain backslash escapes")
    for match in re.finditer(r"url\s*\(", text, re.IGNORECASE):
        if not _CSS_URL.match(text, match.start()):
            raise _refuse(path, "generated CSS has a url( that cannot be checked")
    for match in _CSS_URL.finditer(text):
        if not _local_file(match.group(2), home):
            raise _refuse(
                path,
                f"generated CSS may only use url() for your own files, "
                f"not {match.group(2)[:80]!r}",
            )


# --- entry point -------------------------------------------------------------


def check_generated(path: Path, text: str, *, home: Path) -> None:
    """Raise UnsafeContentError if ``text`` for ``path`` could run or fetch things.

    The rules are chosen by file type; an unknown type gets the strictest
    shared rules (no exec words, no command substitution).
    """
    suffix = path.suffix.lower()
    if suffix == ".lua":
        _check_lua(path, text)
    elif suffix == ".conf":
        _check_conf(path, text)
    elif suffix == ".toml":
        _check_toml(path, text)
    elif suffix in (".json", ".jsonc") or path.name == "config":
        _check_json(path, text)
    elif suffix == ".css":
        _check_css(path, text, home)
    else:
        _check_conf(path, text)
        if re.search(r"\bexec", text):
            raise _refuse(path, "generated file may not mention exec")
