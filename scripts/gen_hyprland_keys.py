#!/usr/bin/env python3
"""Regenerate src/buckwheat/adapters/hyprland_keys.json from Hyprland's stubs.

Usage: python scripts/gen_hyprland_keys.py [STUB] [OUT]

STUB defaults to /usr/share/hypr/stubs/hl.meta.lua (shipped by Hyprland 0.57+),
OUT to the committed data file. The JSON holds every key Hyprland lists with
its raw stub type; the adapter decides which ones it may set. Commit the
result: CI has no Hyprland, and buckwheat falls back to this file when the
stub is not installed.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from buckwheat.adapters.hyprland_keys import DATA_PATH, STUB_PATH, parse_stub


def generate(stub: Path, out: Path) -> int:
    """Write ``out`` from ``stub``; returns the number of keys."""
    keys = parse_stub(stub.read_text(encoding="utf-8"))
    if not keys:
        raise SystemExit(f"{stub}: no HL.ConfigValueTypes fields found")
    data = {
        "_comment": "Generated by scripts/gen_hyprland_keys.py; do not edit.",
        "source": stub.name,
        "keys": dict(sorted(keys.items())),
    }
    out.write_text(json.dumps(data, indent=1) + "\n", encoding="utf-8")
    return len(keys)


def main(argv: list[str]) -> int:
    stub = Path(argv[1]) if len(argv) > 1 else STUB_PATH
    out = Path(argv[2]) if len(argv) > 2 else DATA_PATH
    count = generate(stub, out)
    print(f"wrote {count} keys to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
